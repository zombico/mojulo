#!/usr/bin/env node
/**
 * The flora gap report (docs/flora-gaps.md): what belongs on each kind of ground (era/substrate-flora.js) set against the
 * flora library's own registries, and the gaps ranked. Generated from the tree: `npm run flora-gaps`; a test keeps it
 * current (scripts/flora-gaps.test.js).
 *
 *   node scripts/flora-gaps.mjs [--check]   (--check: exit 1 when the page is stale, write nothing)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { register } from 'node:module';

const HERE = dirname(fileURLToPath(import.meta.url));
export const PAGE = resolve(HERE, '../../docs/flora-gaps.md');

/** The page, as markdown. (The library is read lazily: run alone, the script registers the repo's loader first.) */
export async function floraGapsMd() {
  const { SUBSTRATES, SUBSTRATE_IDS, FORMATION_TURNS } = await import('../lib/graph/era/substrate.js');
  const { ROLES, floraGaps, levelShares, SHARE_FLOOR, WATER_LEVELS, WATERSIDE } = await import('../lib/graph/era/substrate-flora.js');
  const { dry, waterside, shares } = levelShares(), G = floraGaps({ shares }), cell = (m) => [...m.have.map((h) => `\`${h}\``), ...m.want.map((w) => `*${w}*`)].join(', ') || '·';
  const at = (s, r) => G.matrix.find((m) => m.substrate === s && m.role === r);
  return [
    '# Flora gaps',
    '',
    'Generated by `npm run flora-gaps` from `control/lib/graph/era/substrate.js` (what the ground is) and',
    '`control/lib/graph/era/substrate-flora.js` (what belongs on it), set against the flora library\'s own registries.',
    'Do not edit: change the rules or the library and regenerate. Internal: not an MCP surface.',
    '',
    '## The ground',
    '',
    'Its share of a level: averaged over the cube presets\' stage land, each with its own base, grit and formation; dry',
    `as the presets lay it, by the water a word lays (${WATER_LEVELS.join(', ')}: era/out-water.js, averaged), and a level's,`,
    `${WATERSIDE * 100}% of the levels by the water and the rest dry.`,
    '',
    '| substrate | what it is | dry | by the water | share of a level |',
    '| --- | --- | --- | --- | --- |',
    ...SUBSTRATE_IDS.map((s) => `| ${s} | ${SUBSTRATES[s]} | ${(dry[s] * 100).toFixed(1)}% | ${(waterside[s] * 100).toFixed(1)}% | ${(shares[s] * 100).toFixed(1)}% |`),
    '',
    'A cube\'s rock formation turns its soil: ' + Object.entries(FORMATION_TURNS).map(([k, t]) => `${k} (${t.read})`).join('; ') + '.',
    '',
    '## What belongs where',
    '',
    '`code`: in the library. *italic*: wanted, not yet built. ·: nothing belongs there.',
    '',
    `| substrate | ${ROLES.join(' | ')} |`,
    `| --- | ${ROLES.map(() => '---').join(' | ')} |`,
    ...SUBSTRATE_IDS.map((s) => `| ${s} | ${ROLES.map((r) => cell(at(s, r))).join(' | ')} |`),
    '',
    '## Empty slots',
    '',
    'Where nothing in the library grows yet: ' + (G.empty.length ? G.empty.map((x) => `\`${x}\``).join(', ') : 'none') + '.',
    '',
    '## The gaps, ranked',
    '',
    `Ranked by the ground a kind would cover: over the grounds it belongs on, each one's share of a level (at least ${SHARE_FLOOR * 100}%: a ground no level lays yet), × the share of the climates it suits, doubled where it fills an empty slot.`,
    '',
    '| wanted | what it is | on | climates | fills | score |',
    '| --- | --- | --- | --- | --- | --- |',
    ...G.gaps.map((g) => `| ${g.want} | ${g.read} | ${g.substrates.join(', ')} | ${g.climates.join(', ')} | ${g.fills.join(', ') || '·'} | ${g.score} |`),
    '',
  ].join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  register('./mcp-stdio-loader.mjs', import.meta.url);
  const md = await floraGapsMd();
  if (process.argv.includes('--check')) {
    const now = (() => { try { return readFileSync(PAGE, 'utf8'); } catch { return ''; } })();
    if (now !== md) { console.error('stale: npm run flora-gaps'); process.exit(1); }
  } else { writeFileSync(PAGE, md); console.log('→', PAGE); }
}
