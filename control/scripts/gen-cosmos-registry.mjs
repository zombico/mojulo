#!/usr/bin/env node
/**
 * Writes lib/graph/cosmos/registry.generated.js: every facet setting that names a source table, with the values that
 * table holds today (lib/graph/cosmos/read-sources.js). Run it after a source table changes or a facet names a new
 * one; registry.deep.test.js fails until it is run.
 *
 *   node scripts/gen-cosmos-registry.mjs
 */
import { writeFileSync } from 'node:fs';
import { register } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

export function registrySource(sources) {
  const rows = Object.entries(sources).map(([key, row]) => `  ${JSON.stringify(key)}: Object.freeze(${JSON.stringify(row)}),`);
  return `/**
 * GENERATED by scripts/gen-cosmos-registry.mjs, never by hand: each sourced facet setting's values as its table holds
 * them (read-sources.js), held equal to the live read by registry.deep.test.js.
 */
export const GENERATED = Object.freeze({
${rows.join('\n')}
});
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const here = path.dirname(fileURLToPath(import.meta.url));
  register(pathToFileURL(path.join(here, 'mcp-stdio-loader.mjs')).href);
  const { readSources } = await import('../lib/graph/cosmos/read-sources.js');
  const out = fileURLToPath(new URL('../lib/graph/cosmos/registry.generated.js', import.meta.url));
  writeFileSync(out, registrySource(await readSources()));
  process.stdout.write(`wrote ${out}\n`);
  process.exit(0);
}
