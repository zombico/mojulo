#!/usr/bin/env node
/**
 * Writes lib/graph/fauna/behavior/does-table.js: each species' posable behaviors, solved live (entries.js `liveDoes`).
 * The animal entry cards read the table so a catalog load does not build every species' skeleton. Run it after a change
 * to the species, their skeletons or the behavior resolver; does-table.deep.test.js fails until it is run.
 *
 *   node scripts/gen-fauna-does.mjs
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SPECIES } from '../lib/graph/fauna/species.js';
import { liveDoes } from '../lib/graph/fauna/entries.js';

export function doesTableSource() {
  const rows = Object.keys(SPECIES).sort().map((id) => `  ${JSON.stringify(id)}: Object.freeze(${JSON.stringify(liveDoes(id))}),`);
  return `/**
 * GENERATED by scripts/gen-fauna-does.mjs, never by hand: what each species can be minted doing (\`{ <behavior>: <strategy> }\`),
 * the live solve of entries.js \`liveDoes\`, held equal to it by does-table.deep.test.js.
 */
export const DOES_TABLE = Object.freeze({
${rows.join('\n')}
});
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = fileURLToPath(new URL('../lib/graph/fauna/behavior/does-table.js', import.meta.url));
  writeFileSync(out, doesTableSource());
  process.stdout.write(`wrote ${out}\n`);
}
