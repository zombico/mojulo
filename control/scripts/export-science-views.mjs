#!/usr/bin/env node
/**
 * export-science-views — emit the study-view registry for the mojulo.ai
 * science section.
 *
 * The view-vocab cards (lib/graph/views/view-vocab/*.md) are the source of
 * truth; this script is a read-only sweep that pairs each card's frontmatter
 * with its prose and parameter manual and writes one JSON registry the site
 * repo's generator consumes (mojulo-ai/build-science.mjs → science/<id>.html).
 * Same recipes-not-renders posture as the site's exhibits.json: this file is
 * the recipe, the site generator emits the render, and neither is hand-edited.
 *
 *   node scripts/export-science-views.mjs --check                # print inventory, write nothing
 *   node scripts/export-science-views.mjs --out ../mojulo-ai/science-views.json
 *   node scripts/export-science-views.mjs --families science,math --out …
 *
 * Default families: science,math,bio — the create_view study objects. The
 * `world` family (compose_world bases) is deliberately excluded: worlds are
 * places, not indexable explainer subjects.
 *
 * See mojulo-ai/science.plan.md for the site-side half of the pipeline
 * (generator contract, i18n exclusion, sitemap/llms.txt steps).
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { getViewVocabCatalog } from '../lib/graph/views/view-vocab/loader.js';

const DEFAULT_FAMILIES = ['science', 'math', 'bio'];

const args = process.argv.slice(2);
const flag = (name) => {
  const i = args.indexOf(`--${name}`);
  return i === -1 ? null : (args[i + 1] ?? null);
};
const check = args.includes('--check');
const families = (flag('families') ?? DEFAULT_FAMILIES.join(',')).split(',').map((s) => s.trim()).filter(Boolean);
const out = flag('out');

if (!check && !out) {
  console.error('usage: export-science-views.mjs --check | --out <path> [--families science,math,bio]');
  process.exit(1);
}

// The body is depiction prose followed by an optional "## Parameters" manual;
// split them so the site can lay out prose-first pages with the manual as a
// reference block.
function splitBody(body) {
  const marker = '\n## Parameters';
  const at = body.indexOf(marker);
  if (at === -1) return { prose: body.trim(), params: null };
  return { prose: body.slice(0, at).trim(), params: body.slice(at).trim() };
}

const catalog = getViewVocabCatalog();
const views = [...catalog.values()]
  .filter((card) => families.includes(card.family))
  .sort((a, b) => (a.family === b.family ? a.id.localeCompare(b.id) : a.family.localeCompare(b.family)))
  .map((card) => {
    const { prose, params } = splitBody(card.body);
    return {
      id: card.id,
      name: card.name,
      family: card.family,
      entry: card.entry,
      summary: card.summary,
      when: card.when,
      prose,
      params,
    };
  });

const counts = {};
for (const v of views) counts[v.family] = (counts[v.family] ?? 0) + 1;
const countLine = Object.entries(counts).map(([f, n]) => `${f} ${n}`).join(', ');
console.error(`${views.length} views (${countLine})`);
for (const v of views) console.error(`  [${v.family}] ${v.id} — ${v.name}${v.params ? '' : '  (no params section)'}`);

if (check) process.exit(0);

const registry = {
  $comment:
    'Generated by mojulo/control/scripts/export-science-views.mjs from the view-vocab cards — do not hand-edit; re-export from the mojulo repo instead. Consumed by build-science.mjs. EN-only by design: see science.plan.md.',
  generatedAt: new Date().toISOString().slice(0, 10),
  families,
  views,
};

const outPath = path.resolve(out);
writeFileSync(outPath, JSON.stringify(registry, null, 2) + '\n');
console.error(`wrote ${outPath}`);
