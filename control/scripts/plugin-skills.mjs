const FENCE = /^---\s*\n([\s\S]*?)\n---\s*\n?/;

/** A routing card's frontmatter and body (the loader's format; read here so the script needs no server import). */
export function readCard(id) {
  const raw = readFileSync(join(CARDS_DIR, `${id}.md`), 'utf8');
  const m = raw.match(FENCE);
  if (!m) throw new Error(`routing card ${id} has no frontmatter`);
  return { ...JSON.parse(m[1]), body: raw.slice(m[0].length).trim() };
}

/** The card's recognizer quotes, in order. */
const quotesOf = (when) => [...when.matchAll(/"([^"]+)"/g)].map((m) => m[1]);

/** The lead, then the person's own words from the cards, as many as fit the budget. */
export function describe(start) {
  const quotes = start.cards.flatMap((id) => quotesOf(readCard(id).when));
  let text = `${start.lead} Use when the user asks for`;
  const taken = [];
  for (const q of quotes) {
    const next = `${text} ${[...taken, `"${q}"`].join(', ')}.`;
    if (next.length > DESCRIPTION_BUDGET) break;
    taken.push(`"${q}"`);
  }
  return taken.length ? `${text} ${taken.join(', ')}.` : start.lead;
}

