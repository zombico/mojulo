#!/usr/bin/env node
/**
 * The Claude plugin's tiered subagents and its skill's delegation block, generated from the tier table
 * (lib/mcp/tool-tiers.js), so the tool a subagent may call and the tier a tool carries have one source.
 *
 *   plugins/mojulo/agents/mojulo-runner.md   Haiku, low effort: `ride` and `fill` tools
 *   plugins/mojulo/agents/mojulo-maker.md    Sonnet, medium effort: `ride`, `fill` and `judge` tools
 *   plugins/mojulo/agents/mojulo-author.md, mojulo-critic.md, mojulo-assistant.md   the jobs inside a req
 *                                            (gameworld/jobs.js, production.js): `design_game` alone, used only for
 *                                            their job's own view and report; their bodies from the same text the
 *                                            server serves (the lenses, the postures)
 *   plugins/mojulo/skills/mojulo/SKILL.md    the block between the tiers markers: what stays with the main
 *                                            session (`design`) and when to hand work to each subagent
 *
 * Each subagent's `tools` list is exact: it cannot call a tool above its tier. Tools the plugin profile hides,
 * and tools whose tier is deferred, are left out. Model names live here and in the Claude runtime adapter only.
 *
 *   node scripts/plugin-agents.mjs [--check]
 *
 *   --check  exit 1 when a generated file would differ from the one on disk (stale), and write nothing
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TOOL_TIERS } from '../lib/mcp/tool-tiers.js';
import { hiddenInPluginProfile } from '../lib/mcp/plugin-profile.js';
import { LENSES, POSTURES, POSTURE_OF } from '../lib/graph/gameworld/job-words.js';

const HERE = dirname(fileURLToPath(import.meta.url));
export const PLUGIN_DIR = resolve(HERE, '../../plugins/mojulo');

// plugin.json names the plugin and its server `mojulo`: Claude Code calls the tools mcp__plugin_mojulo_mojulo__<tool>.
const TOOL_PREFIX = 'mcp__plugin_mojulo_mojulo__';
const PLUGIN_ENV = { MOJULO_DISTRIBUTION: 'claude-plugin' };

export const SKILL_BEGIN = '<!-- tiers:begin (generated by control/scripts/plugin-agents.mjs) -->';
export const SKILL_END = '<!-- tiers:end -->';

/** Plugin-visible tools of the given tiers, sorted. */
export function toolsOf(tiers) {
  return Object.entries(TOOL_TIERS)
    .filter(([name, tier]) => tiers.includes(tier) && !hiddenInPluginProfile(name, PLUGIN_ENV))
    .map(([name]) => name)
    .sort();
}

const code = (names) => names.map((n) => `\`${n}\``).join(', ');

function agentFile({ name, description, model, effort, tiers, body }) {
  const tools = toolsOf(tiers);
  return [
    '---',
    `name: ${name}`,
    `description: ${JSON.stringify(description)}`, // quoted: the text carries ': ' and apostrophes
    `model: ${model}`,
    `effort: ${effort}`,
    // ToolSearch first: Claude Code defers MCP tool schemas, and a subagent without it cannot load the mojulo tools
    // its list names, so it would have none at all (seen with --agent on CLI 2.1.288).
    `tools: ${['ToolSearch', ...tools.map((t) => TOOL_PREFIX + t)].join(', ')}`,
    '---',
    '',
    `<!-- Generated by control/scripts/plugin-agents.mjs from control/lib/mcp/tool-tiers.js. Do not edit by hand. -->`,
    '',
    body.trim(),
    '',
    `Your mojulo tools: ${code(tools)}.`,
    '',
  ].join('\n');
}

export function runnerAgent() {
  return agentFile({
    name: 'mojulo-runner',
    description:
      "Runs mojulo's light work on a fast model. Use proactively for batches of mojulo calls that need no authoring: "
      + 'exports in several formats, measuring or diffing made things, listing and fetching refs, gathering items into a '
      + 'stash, filing a view whose spec is already decided. Not for writing recipes, worlds, games, plans or publications.',
    model: 'haiku',
    effort: 'low',
    tiers: ['ride', 'fill'],
    body: `
You run mojulo calls the main session has already decided on. Do exactly the calls in your brief, in order.

- Report what each call returned that the main session needs: refs, file paths, numbers, refusals. No commentary.
- When a call refuses or asks for a choice your brief does not settle, stop and report it with the tool's own words.
  Do not pick for the user, and do not reach for a tool you were not given.
- Never say a picture, model or level looks right: you ran the machine gate at most, never the eyes gate.`,
  });
}

export function makerAgent() {
  return agentFile({
    name: 'mojulo-maker',
    description:
      'Authors and revises one mojulo recipe from a clear brief: a sketch or diagram, a score, a motion clip, a cover, a '
      + 'solid, a fabrication, a world or a city plan, a level\'s ground. Use proactively when the design is settled and one artifact needs writing or revising. '
      + 'Not for designing games, plans, publications or research theses.',
    model: 'sonnet',
    effort: 'medium',
    tiers: ['ride', 'fill', 'judge'],
    body: `
You author or revise one mojulo artifact to the brief the main session gives you.

- Read the vocab card or manual the tool points to before you write the recipe; iterate on the stored recipe in place
  (\`update_sketch\`, \`edit_solid\`, \`update_beats\`) instead of minting again.
- Report the ref, what you made or changed, and what a person should look at to pass the eyes gate. Never claim it passed.
- When the brief leaves a creative choice open that changes what the user gets, stop and ask the main session.`,
  });
}

/** A job's agent (the jobs inside a req): `design_game` alone, for its own view and its report. */
function jobAgentFile({ name, description, model, effort, body }) {
  return [
    '---',
    `name: ${name}`,
    `description: ${JSON.stringify(description)}`,
    `model: ${model}`,
    `effort: ${effort}`,
    `tools: ToolSearch, ${TOOL_PREFIX}design_game`,
    '---',
    '',
    '<!-- Generated by control/scripts/plugin-agents.mjs from control/lib/graph/gameworld/job-words.js. Do not edit by hand. -->',
    '',
    body.trim(),
    '',
  ].join('\n');
}

// what every job agent does with its brief, whatever its kind
const JOB_COMMON = `
You hold one seat in a mojulo production: your brief's \`role\`. The director may keep you in it beat after beat, so
what you did earlier in this conversation is your precedent: build on it, and do not repeat it.

- Read your view first, exactly as your brief's \`read\` says (it carries \`as\`: your job). It holds your unit's pages,
  its remit, its precedent, the intent it was asked for with, the crew's notebook and your brief. Read the cards it names.
- \`design_game\` is yours for that view and your report only: never another unit's pages, never a run, never a verdict.
- Report once, with your brief's \`submit\` call. If it is refused, read the reason, fix it and submit again (three tries).
- Never say it looks right: the machine gate is the server's, the eyes gate the creator's.`;

export function authorAgent() {
  return jobAgentFile({
    name: 'mojulo-author',
    description: 'Works one author job inside a mojulo req: writes one unit\'s pages (a level, the foes, the story …) to its remit, with a reason for every choice. Spawn it with the job\'s brief; keep one per role across beats. Its brief\'s tier names the model to give it: design → opus, judge → sonnet.',
    model: 'sonnet',
    effort: 'medium',
    body: `
You are an author. Write your unit so it does what its remit asks, above all its one new idea.
${JOB_COMMON}
- Write only the paths in your brief's \`writes\`, as one patch, in the recipe's own words (the cards say them).
- Give every decision a \`because\` that ties it to the remit, the intent or the precedent. A choice you cannot explain
  is one the seed made: make it yours or leave it out.
- What the remit asks that no word of the recipe reaches goes in \`asks\`: say the gap, never fake it.
- In a crew, post to the notebook what the others need (\`req: { id, job, post }\`): a size, a rhythm, a constraint.`,
  });
}

export function criticAgent() {
  return jobAgentFile({
    name: 'mojulo-critic',
    description: 'Works one critic job inside a mojulo req: reads what was made with its lens (design, play or look) and reports findings. Never writes. Spawn it with the job\'s brief, fresh: a critic reads without the maker\'s reasoning.',
    model: 'sonnet',
    effort: 'medium',
    body: `
You are a critic. Read what was made with your brief's \`lens\`, never the maker's reasoning.
${JOB_COMMON}
- Your lenses: ${Object.entries(LENSES).map(([k, v]) => `${k}, ${v}`).join(' ')}
- Report \`findings\`: each one thing, said plainly, with the \`part\` it is about. No patch.`,
  });
}

export function assistantAgent() {
  return jobAgentFile({
    name: 'mojulo-assistant',
    description: 'Works the assistant director job inside a mojulo req: reads what the crew made in the posture its director\'s style sets (assistive, strict, elevating) and recommends pass-up, rework or elevate, with reasons. It never decides. Keep one per world.',
    model: 'sonnet',
    effort: 'medium',
    body: `
You are the assistant director. You prepare the director's call; you never make it.
${JOB_COMMON}
- Your posture is in your brief. Ask its question of everything you read:
${Object.entries(POSTURE_OF).map(([style, posture]) => `  - ${posture} (the ${style} director's): ${POSTURES[posture]}`).join('\n')}
- Report \`recommend\` (pass-up, rework or elevate) with \`reasons\`, each one you could defend to the director; \`fixes\`
  for a rework, \`bolder\` (one angle, in a sentence) to elevate.`,
  });
}

export function skillBlock() {
  const design = toolsOf(['design']);
  return [
    SKILL_BEGIN,
    '**Sharing the work across models (Claude Code).** Spend the strongest model on design and run the rest light,',
    "so the user's usage limits build more:",
    '',
    `- Keep design with you: ${code(design)}.`,
    '- Hand one artifact to write or revise, with a clear brief, to the `mojulo-maker` subagent.',
    '- Hand a batch of decided calls (exports, measures, lists, gathers) to the `mojulo-runner` subagent.',
    '- A routing card or catalyst found by `semantic_search`, and every catalyst `list_catalysts`, `get_catalyst` and',
    '  `recommend_catalysts` return, carries a `tier`: `design` stays with you, `judge` goes to `mojulo-maker`, `ride` and',
    '  `fill` to `mojulo-runner`. A skill you materialize from a catalyst runs where its tier says.',
    '- Read a manual yourself when you are about to author with it: what a subagent reads stays in its context.',
    '- Make a single quick call yourself: starting a subagent costs more than one light call.',
    '- A req\'s jobs go to their own agents, each with its brief: an author to `mojulo-author`, a critic to `mojulo-critic`',
    '  (fresh), the assistant director to `mojulo-assistant`. Keep one agent per `role` and continue it for the next beat.',
    SKILL_END,
  ].join('\n');
}

/** The skill with its generated block replaced (or appended when the markers are absent). */
export function skillWithBlock(skill) {
  const block = skillBlock();
  const i = skill.indexOf(SKILL_BEGIN);
  const j = skill.indexOf(SKILL_END);
  if (i >= 0 && j > i) return skill.slice(0, i) + block + skill.slice(j + SKILL_END.length);
  return `${skill.trimEnd()}\n\n${block}\n`;
}

export function generated() {
  const skillPath = join(PLUGIN_DIR, 'skills/mojulo/SKILL.md');
  return {
    [join(PLUGIN_DIR, 'agents/mojulo-runner.md')]: runnerAgent(),
    [join(PLUGIN_DIR, 'agents/mojulo-maker.md')]: makerAgent(),
    [join(PLUGIN_DIR, 'agents/mojulo-author.md')]: authorAgent(),
    [join(PLUGIN_DIR, 'agents/mojulo-critic.md')]: criticAgent(),
    [join(PLUGIN_DIR, 'agents/mojulo-assistant.md')]: assistantAgent(),
    [skillPath]: skillWithBlock(readFileSync(skillPath, 'utf8')),
  };
}

function readOr(path) {
  try {
    return readFileSync(path, 'utf8');
  } catch {
    return null;
  }
}

export function staleFiles() {
  return Object.entries(generated()).filter(([path, text]) => readOr(path) !== text).map(([path]) => path);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const stale = staleFiles();
    for (const path of stale) console.error(`stale: ${path} (node scripts/plugin-agents.mjs)`);
    process.exit(stale.length ? 1 : 0);
  }
  for (const [path, text] of Object.entries(generated())) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
    console.log(`wrote ${path}`);
  }
}
