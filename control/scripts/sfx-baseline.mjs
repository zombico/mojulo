#!/usr/bin/env node
/**
 * The SFX shelf's baseline (lib/graph/sfx-shelf/baseline.js): every cue of every set rendered as an export renders it
 * and measured on the yardstick (sfx-shelf/measure.js). The numbers are the floor a better voice is held to. Generated:
 * `npm run sfx-baseline`; a deep test re-measures the sets against it (sfx-shelf/baseline.deep.test.js).
 *
 *   node scripts/sfx-baseline.mjs [--check] [--wav <dir>]
 *     --check       exit 1 when the page is stale, write nothing
 *     --wav <dir>   also write each cue, and its per-hit variants 1 and 2, as <dir>/<set>/<cue>[-vN].wav (to listen)
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const PAGE = resolve(HERE, '../lib/graph/sfx-shelf/baseline.js');

/** The measured sets: { <set>: { <cue>: measures } }. */
export async function measureSets({ wav = null } = {}) {
  const { SETS, setManifest } = await import('../lib/graph/sfx-shelf/sets.js');
  const { renderSound } = await import('../lib/graph/sfx-shelf/measure.js');
  const out = {};
  for (const name of Object.keys(SETS)) {
    const m = setManifest(name);
    out[name] = {};
    for (const cue of Object.keys(m.cues)) {
      const { wav: bytes, ...measures } = await renderSound(m, cue);
      out[name][cue] = measures;
      if (wav) {
        const dir = join(wav, name);
        mkdirSync(dir, { recursive: true });
        writeFileSync(join(dir, `${cue}.wav`), bytes);
        for (const variant of [1, 2]) writeFileSync(join(dir, `${cue}-v${variant}.wav`), (await renderSound(m, cue, { variant })).wav);
      }
    }
  }
  return out;
}

const row = (cue, v) => `    '${cue}': { layers: ${v.layers}, ms: ${v.ms}, centroidHz: ${v.centroidHz}, crestDb: ${v.crestDb}, bands: { ${Object.entries(v.bands).map(([b, x]) => `${b}: ${x}`).join(', ')} } },`;

/** The page, as JS. */
export async function baselineJs(measured) {
  const sets = measured ?? (await measureSets());
  return [
    '/**',
    ' * sfx-shelf/baseline — every set\'s cues measured on the yardstick (measure.js), rendered as an export renders them.',
    ' * Generated by `npm run sfx-baseline` (scripts/sfx-baseline.mjs): do not edit. The numbers are the floor a better',
    ' * voice of the same sound is held to; a deep test re-measures the sets against them (baseline.deep.test.js).',
    ' */',
    '',
    'export const BASELINE = Object.freeze({',
    ...Object.entries(sets).flatMap(([name, cues]) => [`  ${name}: {`, ...Object.entries(cues).map(([c, v]) => row(c, v)), '  },']),
    '});',
    '',
  ].join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2), at = args.indexOf('--wav');
  const wav = at >= 0 ? resolve(args[at + 1]) : null;
  const js = await baselineJs(await measureSets({ wav }));
  if (args.includes('--check')) {
    let now = '';
    try { now = readFileSync(PAGE, 'utf8'); } catch {}
    if (now !== js) { console.error('sfx-baseline: lib/graph/sfx-shelf/baseline.js is stale; run `npm run sfx-baseline`'); process.exit(1); }
    console.log('sfx-baseline: current');
  } else {
    writeFileSync(PAGE, js);
    console.log(`sfx-baseline: wrote ${PAGE}${wav ? `, and the WAVs under ${wav}` : ''}`);
  }
}
