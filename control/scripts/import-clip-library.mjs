#!/usr/bin/env node
/**
 * import-clip-library.mjs — read a humanoid ANIMATION LIBRARY (a glTF with a skin and its clips: Quaternius's
 * Universal Animation Library, a Godot or Blender export) into a hub library mojulo's rigs play
 * (lib/graph/figures/clip-library.js hubClips): every named clip as world turns from the library's bind T-pose, in
 * the native frame, keyed by VRM bone. The hub is what ships (lib/graph/figures/library/<id>.js), never the
 * library's file; a library whose licence forbids redistribution is imported for the operator's own use only.
 *
 *   node scripts/import-clip-library.mjs <library.gltf> --map quaternius-ual [--clips A,B,…] [--fps 24]
 *     [--id <id>] [--licence CC0] [--source "<who, where>"] [--out <file.js>]
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { hubClips, LIBRARY_MAPS } from '../lib/graph/figures/clip-library.js';

const args = process.argv.slice(2), arg = (k, d) => { const i = args.indexOf(`--${k}`); return i >= 0 ? args[i + 1] : d; };
const file = args.find((a) => !a.startsWith('--') && !args[args.indexOf(a) - 1]?.startsWith('--'));
if (!file) { console.error('usage: import-clip-library.mjs <library.gltf> --map <map> [--clips A,B] [--fps 24] [--id id] [--licence L] [--source S] [--out file]'); process.exit(1); }
const mapId = arg('map', 'quaternius-ual'), map = LIBRARY_MAPS[mapId];
if (!map) { console.error(`no map '${mapId}' (maps: ${Object.keys(LIBRARY_MAPS).join(', ')})`); process.exit(1); }
const gltf = JSON.parse(readFileSync(file, 'utf8'));
if (!gltf.buffers?.[0]?.uri || gltf.buffers[0].uri.startsWith('data:')) { console.error('the library must be a .gltf with its buffer beside it'); process.exit(1); }
const bin = readFileSync(join(dirname(resolve(file)), gltf.buffers[0].uri));
const clips = arg('clips') ? arg('clips').split(',') : undefined;
const lib = hubClips(gltf, bin, { map, clips, fps: Number(arg('fps', 24)) });
const id = arg('id', mapId);
const out = { id, map: mapId, licence: arg('licence', 'unknown'), source: arg('source', file), rest: lib.rest, clips: lib.clips };
const dest = arg('out', resolve('lib/graph/figures/library', `${id}.js`));
mkdirSync(dirname(dest), { recursive: true });
const head = `/** ${id}: a hub clip library (lib/graph/figures/clip-library.js), generated by scripts/import-clip-library.mjs; do not
 *  edit. Source: ${out.source}. Licence: ${out.licence}. */
`;
writeFileSync(dest, `${head}export default ${JSON.stringify(out)};\n`);
console.log(`${dest}: ${Object.keys(out.clips).length} clips (${Object.keys(out.clips).join(', ')}), ${(JSON.stringify(out).length / 1024).toFixed(0)} KB`);
