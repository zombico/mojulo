#!/usr/bin/env node
/**
 * Writes lib/graph/mind/mind-table.js: what every named mind and every species' mind does in each situation, solved
 * live (lib/graph/mind/table.js). Run it after a change to the mind vocabulary, the strategies, the presets, or the
 * fauna tags and capabilities; mind-table.deep.test.js fails until it is run.
 *
 *   node scripts/gen-mind-table.mjs
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { liveMindTable } from '../lib/graph/mind/table.js';

export function mindTableSource() {
  const { presets, fauna } = liveMindTable();
  const rows = (o) => Object.entries(o).map(([id, row]) => `    ${JSON.stringify(id)}: Object.freeze(${JSON.stringify(row)}),`).join('\n');
  return `/**
 * GENERATED by scripts/gen-mind-table.mjs, never by hand: what each named mind and each species' mind does in every
 * situation (\`{ <situation>: <strategy> | [<repertoire>] }\`), the live solve of table.js \`liveMindTable\`, held
 * equal to it by mind-table.deep.test.js.
 */
export const MIND_TABLE = Object.freeze({
  presets: Object.freeze({
${rows(presets)}
  }),
  fauna: Object.freeze({
${rows(fauna)}
  }),
});
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = fileURLToPath(new URL('../lib/graph/mind/mind-table.js', import.meta.url));
  writeFileSync(out, mindTableSource());
  process.stdout.write(`wrote ${out}\n`);
}
