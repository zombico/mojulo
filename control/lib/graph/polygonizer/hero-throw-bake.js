/**
 * hero-throw-bake — the throw library (hero-throw.js) baked into sticks: each technique solved on a rig (the bake's hero:
 * BAKE_HERO, the canonical male), sampled a frame every FRAME seconds into the joints a contest page poses its athletes by
 * (contest/athlete-pose.js's stick: pelvis, neck, and per side shoulder, elbow, wrist, hip, knee, ankle), millimetres off
 * the pelvis's place at the throw's start in the thrower's frame (+x right, +y the target, +z up), the ball's centre while
 * held, the release as solved and as the library launches it. scripts/throw-sticks.mjs writes the module
 * (contest/throw-sticks.data.js) that contest/throw-sticks.js plays. Pure and deterministic.
 */
import { rigNodesAt } from './station-loft-rig.js';
import { heroThrow, heldBall, THROW_NAMES, THROWS } from './hero-throw.js';

/** the hero the library is baked on */
export const BAKE_HERO = Object.freeze({ cast: 'male', head: 'anime' });
/** a frame every FRAME seconds (the clip's own last frame kept) */
export const FRAME = 1 / 30;
const mm = (v) => Math.round(v * 1000);

/** the stick's joints from a rig's posed nodes (the rig's own names for the legs: its hip, knee and hock) */
function stickOf(R, n) {
  const j = { pelvis: n.pelvisHub, neck: n.neckHub };
  for (const S of ['L', 'R']) {
    const L = R.legs[S];
    Object.assign(j, { [`shoulder${S}`]: n[`shoulder${S}`], [`elbow${S}`]: n[`elbow${S}`], [`wrist${S}`]: n[`wrist${S}`], [`hip${S}`]: n[L.hip], [`knee${S}`]: n[L.knee], [`ankle${S}`]: n[L.hock] });
  }
  return j;
}
/** the stick's joint order in a baked frame */
export const STICK_JOINTS = Object.freeze(['pelvis', 'neck', 'shoulderL', 'elbowL', 'wristL', 'hipL', 'kneeL', 'ankleL', 'shoulderR', 'elbowR', 'wristR', 'hipR', 'kneeR', 'ankleR']);

/** Each technique (all, or `only`) solved on R and sampled: { <name>: { seconds, release: { u, at, spec, clip }, ball, frames: [[x, y, z]×joints, ball?] } } */
export function bakeThrowSticks(R, { only = null } = {}) {
  const out = {};
  for (const name of only ?? THROW_NAMES) {
    const T = heroThrow(name, R), N = Math.max(2, Math.round(T.seconds / FRAME));
    const o = rigNodesAt(R, T.clip.fn(0)).nodes.pelvisHub, rel = (p) => [mm(p[0] - o[0]), mm(p[1] - o[1]), mm(p[2] - o[2])];
    const frames = [];
    for (let i = 0; i <= N; i++) {
      const u = i / N, n = rigNodesAt(R, T.clip.fn(u)).nodes, s = stickOf(R, n);
      frames.push([...STICK_JOINTS.map((k) => rel(s[k])), u <= T.release.t ? rel(heldBall(R, T.clip, u, T.ball.side, T.ball.centreRest)) : null]);
    }
    out[name] = { says: THROWS[name].says, sports: THROWS[name].sports, seconds: T.seconds, side: T.side, hands: T.hands,
      ball: { id: T.ball.id, r: T.ball.r, mass: T.ball.mass, grip: T.ball.grip },
      release: { u: T.release.t, at: rel(T.release.at), spec: { speed: T.release.spec.speed, elevation: T.release.spec.elevation, spin: { axis: T.release.spec.spin.axis, rps: T.release.spec.spin.rps } }, clip: { speed: T.release.speed, elevation: T.release.elevation } },
      laws: T.checks.laws, frames };
  }
  return out;
}

/** the baked library as the module's source */
export function renderThrowSticksModule(baked) {
  return `// GENERATED by scripts/throw-sticks.mjs from lib/graph/polygonizer/hero-throw.js (the throws solved on the canonical male
// hero, hero-throw-bake.js): do not edit; node scripts/throw-sticks.mjs. Millimetres off the pelvis at the throw's start,
// the thrower's frame (+x right, +y the target, +z up); each frame the joints in STICK_JOINTS's order, then the ball (null
// once it is gone).
export const THROW_STICK_JOINTS = ${JSON.stringify(STICK_JOINTS)};
export const THROW_STICK_FRAME = ${JSON.stringify(FRAME)};
export const THROW_STICKS = ${JSON.stringify(baked)};
`;
}
